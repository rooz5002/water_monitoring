#!/usr/bin/env python3
"""
export_model.py
By Dr. Amir A Mokhtarzadeh
Aug 2026
---------------
Exports the trained PSO-ASVM (scikit-learn SVC with RBF kernel) plus the
StandardScaler into a single C header, `model.h`, that the ESP32(LilyGo 7000) benchmark
sketch (`svm_benchmark.ino`) compiles in directly.

It also embeds the held-out test set (raw feature values) together with the
labels scikit-learn predicts for them, so the ESP32 can VERIFY that its on-device
inference reproduces scikit-learn exactly before you trust the timing numbers.

Edit the LOAD section below to match filenames):
  - the fitted StandardScaler          (fitted on the 787-sample training features)
  - the fitted SVC                     (kernel='rbf', C=199.526, gamma=1.318, fitted
                                        on the *standardised* training features)
  - X_test  : raw test features, shape (n, 4), column order [pH, turbidity, EC, TDS]

Feature column order MUST be [pH, turbidity(NTU), EC(uS/cm), TDS(mg/L)] and TDS in
mg/L (i.e. already multiplied by 1000 if sensor returns g/L), matching our
paper's equation (1).

USAGE:
  python export_model.py            # single-precision (float32) -> what must be  deployed
  python export_model.py --double   # only if we deploy in double precision

running it (needs numpy + scikit-learn + joblib), then copy the
generated `model.h` next to the .ino file.
"""

import argparse
import numpy as np

# ----------------------------------------------------------------------------
# LOAD SECTION  --  EDIT THESE LINES TO POINT AT YOUR OWN SAVED OBJECTS
# ----------------------------------------------------------------------------
# The three objects below are all you need. Two common ways to get them:
#
#   (A) If you saved them with joblib:
#         import joblib
#         scaler = joblib.load("scaler.joblib")
#         svc    = joblib.load("svc.joblib")
#         X_test = np.load("X_test.npy")
#
#   (B) If you have a single fitted Pipeline([("scaler",...),("svc",...)]):
#         import joblib
#         pipe   = joblib.load("pipeline.joblib")
#         scaler = pipe.named_steps["scaler"]
#         svc    = pipe.named_steps["svc"]
#         X_test = np.load("X_test.npy")
#
# Replace the three assignments below with whichever applies to you.
import joblib
scaler = joblib.load("scaler.joblib")
svc    = joblib.load("svc.joblib")
X_test = np.load("X_test.npy").astype(np.float64)
# ----------------------------------------------------------------------------


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--double", action="store_true",
                    help="emit double-precision arrays (default: float32)")
    ap.add_argument("-o", "--out", default="model.h")
    args = ap.parse_args()

    ctype = "double" if args.double else "float"

    # Resolved numeric gamma (handles gamma='scale'/'auto' too)
    gamma = float(getattr(svc, "_gamma", svc.gamma))

    sv        = np.asarray(svc.support_vectors_, dtype=np.float64)   # (n_SV, n_feat), standardised space
    dual      = np.asarray(svc.dual_coef_,       dtype=np.float64)   # (n_class-1, n_SV)
    intercept = np.asarray(svc.intercept_,       dtype=np.float64)   # (n_pairs,)
    n_support = np.asarray(svc.n_support_,        dtype=np.int32)     # (n_class,)
    classes   = np.asarray(svc.classes_)
    mean      = np.asarray(scaler.mean_,  dtype=np.float64)
    scale     = np.asarray(scaler.scale_, dtype=np.float64)

    n_sv, n_feat = sv.shape
    n_class = len(classes)
    n_pairs = n_class * (n_class - 1) // 2

    # scikit-learn predictions on the RAW test set (scale then predict)
    Xs = (X_test - mean) / scale
    y_pred = svc.predict(Xs)
    cls_to_idx = {c: i for i, c in enumerate(classes)}
    y_idx = np.array([cls_to_idx[c] for c in y_pred], dtype=np.int32)
    n_test = X_test.shape[0]

    # sanity: dual_coef_ must be (n_class-1, n_SV)
    assert dual.shape == (n_class - 1, n_sv), dual.shape
    assert intercept.shape[0] == n_pairs, intercept.shape

    fmt = "%.9g" if ctype == "float" else "%.17g"

    def arr(name, flat):
        s = ", ".join(fmt % v for v in flat)
        return "const %s %s[] = { %s };\n" % (ctype, name, s)

    def iarr(name, flat):
        s = ", ".join(str(int(v)) for v in flat)
        return "const int %s[] = { %s };\n" % (name, s)

    with open(args.out, "w") as f:
        f.write("// Auto-generated by export_model.py -- do not edit by hand.\n")
        f.write("// Model: PSO-ASVM (RBF SVC) + StandardScaler.\n")
        f.write("#ifndef MODEL_H\n#define MODEL_H\n\n")
        f.write("#define N_FEATURES %d\n" % n_feat)
        f.write("#define N_CLASSES  %d\n" % n_class)
        f.write("#define N_SV       %d\n" % n_sv)
        f.write("#define N_PAIRS    %d\n" % n_pairs)
        f.write("#define N_TEST     %d\n\n" % n_test)
        f.write("const %s GAMMA = %s;\n\n" % (ctype, fmt % gamma))
        f.write(arr("SCALER_MEAN", mean))
        f.write(arr("SCALER_SCALE", scale))
        f.write(iarr("N_SUPPORT", n_support))
        f.write("\n// Support vectors (standardised space), row-major [N_SV][N_FEATURES]\n")
        f.write(arr("SV", sv.reshape(-1)))
        f.write("\n// Dual coefficients, row-major [N_CLASSES-1][N_SV]\n")
        f.write(arr("DUAL", dual.reshape(-1)))
        f.write("\n// Intercepts, one per class pair (libsvm order)\n")
        f.write(arr("INTERCEPT", intercept))
        f.write("\n// Held-out test set: RAW features, row-major [N_TEST][N_FEATURES]\n")
        f.write(arr("X_TEST", X_test.reshape(-1)))
        f.write("\n// scikit-learn's predicted class index (0..N_CLASSES-1) for each test row\n")
        f.write(iarr("Y_SKLEARN", y_idx))
        f.write("\n#endif // MODEL_H\n")

    print("Wrote %s (%s precision)" % (args.out, ctype))
    print("  gamma        = %g" % gamma)
    print("  n_support    = %s  (sum = %d support vectors)" % (list(n_support), n_sv))
    print("  n_features   = %d, n_classes = %d, n_pairs = %d" % (n_feat, n_class, n_pairs))
    print("  test rows    = %d, class order = %s" % (n_test, list(classes)))
    print("  On device you should see 0 mismatches vs scikit-learn (a few boundary")
    print("  samples may differ under float32 -- that is expected and worth noting).")


if __name__ == "__main__":
    main()
